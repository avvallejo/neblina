// Local development database only. All fixtures and writes are rolled back.
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
const {pool}=require('../src/db');
const {cashExpense}=require('../src/services/cashExpenses');
const {drawerSql}=require('../src/services/cashDrawer');
const {registrarCompra}=require('../src/services/purchases');
const A=require('../src/services/accounting');
(async()=>{
 assert.equal(process.env.NODE_ENV,'development');const c=await pool.connect();
 try{
  await c.query('BEGIN');const q=c.query.bind(c);
  const {rows:[u]}=await q('SELECT id,sucursal_id FROM usuarios WHERE sucursal_id IS NOT NULL LIMIT 1');
  const s=u.sucursal_id,ctx={sucursalId:s,usuarioId:u.id};
  await q('DELETE FROM cierres_mes WHERE sucursal_id=$1',[s]);
  await q('UPDATE turnos SET cerrado_en=now() WHERE sucursal_id=$1 AND cerrado_en IS NULL',[s]);
  const {rows:[t]}=await q('INSERT INTO turnos(sucursal_id,abierto_por,fondo_inicial) VALUES($1,$2,1000) RETURNING id',[s,u.id]);
  const period=A.hoyMx().slice(0,7);const before=await A.estadoResultados(q,s,period);
  const body={solicitudId:randomUUID(),concepto:'Jabón prueba',monto:80,referencia:'Remisión prueba'};
  const gasto=await cashExpense(c,{...ctx,body});assert.equal(gasto.turno_id,t.id);assert.equal(gasto.pagado,true);
  const replay=await cashExpense(c,{...ctx,body});assert.equal(replay.id,gasto.id);
  assert.equal(Number((await q(drawerSql,[s])).rows[0].salidas_turno),80);
  await assert.rejects(()=>cashExpense(c,{...ctx,body:{...body,monto:90}}),e=>e.status===409);
  await assert.rejects(()=>cashExpense(c,{...ctx,body:{...body,solicitudId:randomUUID(),referencia:null}}),e=>e.status===400);
  const inv=await A.cuentaPorClave(q,s,'compra_insumos');
  await assert.rejects(()=>cashExpense(c,{...ctx,body:{...body,solicitudId:randomUUID(),cuentaContableId:inv.id}}),e=>e.status===400);
  const {rows:[cat]}=await q('SELECT id FROM categorias_materia_prima WHERE sucursal_id=$1 LIMIT 1',[s]);
  const {rows:[m]}=await q("INSERT INTO materias_primas(nombre,categoria_id,unidad,stock_actual,stock_minimo,costo_unitario,requiere_lote,sucursal_id) VALUES('Insumo pago prueba',$1,'pieza',0,0,20,false,$2) RETURNING id",[cat.id,s]);
  const lote=await registrarCompra(c,{materiaId:m.id,...ctx,body:{cantidadComprada:10,unidad:'pieza',costoTotal:200,pagado:false}});
  const {rows:[pendiente]}=await q('SELECT * FROM egresos WHERE lote_id=$1',[lote.id]);
  const pay={solicitudId:randomUUID(),monto:200,nota:'Proveedor sin recibo; entrega verificada'};
  await assert.rejects(()=>cashExpense(c,{...ctx,purchaseId:pendiente.id,body:{...pay,monto:199}}),e=>e.status===409);
  await assert.rejects(()=>cashExpense(c,{...ctx,purchaseId:randomUUID(),body:pay}),e=>e.status===404);
  const paid=await cashExpense(c,{...ctx,purchaseId:pendiente.id,body:pay});
  assert.equal(paid.id,pendiente.id);assert.equal(paid.lote_id,lote.id);assert.equal(paid.pagado,true);assert.equal(paid.usuario_id,pendiente.usuario_id);
  assert.equal(A.fechaISO(paid.fecha),A.fechaISO(pendiente.fecha));
  assert.equal(Number((await q('SELECT stock_actual FROM materias_primas WHERE id=$1',[m.id])).rows[0].stock_actual),10);
  assert.equal(Number((await q('SELECT count(*) n FROM egresos WHERE lote_id=$1',[lote.id])).rows[0].n),1);
  assert.equal((await cashExpense(c,{...ctx,purchaseId:paid.id,body:pay})).id,paid.id);
  await assert.rejects(()=>cashExpense(c,{...ctx,purchaseId:paid.id,body:{...pay,solicitudId:randomUUID()}}),e=>e.status===409);
  await assert.rejects(()=>cashExpense(c,{...ctx,purchaseId:gasto.id,body:{...pay,solicitudId:randomUUID()}}),e=>e.status===404);
  const drawer=(await q(drawerSql,[s])).rows[0];assert.equal(Number(drawer.salidas_turno),280);assert.equal(Number(drawer.num_salidas_turno),2);
  const after=await A.estadoResultados(q,s,period);assert.equal(A.round2(before.utilidadNeta-after.utilidadNeta),80);
  await q('SAVEPOINT compras_caja');
  await q("UPDATE materias_primas SET presentacion_cantidad=6,presentacion_unidad='pieza',presentacion_nombre='caja' WHERE id=$1",[m.id]);
  const receive={solicitudId:randomUUID(),cantidadComprada:12,unidad:'pieza',costoTotal:180,pagado:true,referencia:'Galletas 12'};
  const compra=await cashExpense(c,{...ctx,materiaId:m.id,body:receive});
  assert.equal(compra.pagado,true);assert.equal(compra.turno_id,t.id);
  assert.equal((await cashExpense(c,{...ctx,materiaId:m.id,body:receive})).id,compra.id);
  let stock=(await q('SELECT stock_actual,costo_unitario FROM materias_primas WHERE id=$1',[m.id])).rows[0];
  assert.equal(Number(stock.stock_actual),22);assert.equal(Number(stock.costo_unitario),15);
  assert.equal(Number((await q(drawerSql,[s])).rows[0].salidas_turno),460);
  const credit={solicitudId:randomUUID(),paquetes:2,costoTotal:120,pagado:false,nota:'Entrega pendiente de pago'};
  const deuda=await cashExpense(c,{...ctx,materiaId:m.id,body:credit});assert.equal(deuda.pagado,false);assert.equal(deuda.cuenta_dinero_id,null);
  assert.equal(Number((await q(drawerSql,[s])).rows[0].salidas_turno),460);
  assert.equal(Number((await q('SELECT stock_actual FROM materias_primas WHERE id=$1',[m.id])).rows[0].stock_actual),34);
  await cashExpense(c,{...ctx,purchaseId:deuda.id,body:{solicitudId:randomUUID(),monto:120,referencia:'Liquidación'}});
  assert.equal(Number((await q(drawerSql,[s])).rows[0].salidas_turno),580);
  assert.equal(Number((await q('SELECT stock_actual FROM materias_primas WHERE id=$1',[m.id])).rows[0].stock_actual),34);
  assert.equal((await A.estadoResultados(q,s,period)).utilidadNeta,after.utilidadNeta);
  await assert.rejects(()=>cashExpense(c,{...ctx,materiaId:m.id,body:{...receive,cantidadComprada:13}}),e=>e.status===409);
  await assert.rejects(()=>cashExpense(c,{...ctx,materiaId:randomUUID(),body:{...receive,solicitudId:randomUUID()}}),e=>e.status===404);
  await assert.rejects(()=>cashExpense(c,{...ctx,materiaId:m.id,body:{...receive,solicitudId:randomUUID(),pagado:'false'}}),e=>e.status===400);
  await q('ROLLBACK TO SAVEPOINT compras_caja');
  await q('UPDATE egresos SET anulado=true WHERE id=$1',[gasto.id]);assert.equal(Number((await q(drawerSql,[s])).rows[0].salidas_turno),200);
  await q('UPDATE turnos SET cerrado_en=now() WHERE id=$1',[t.id]);
  await assert.rejects(()=>cashExpense(c,{...ctx,body:{...body,solicitudId:randomUUID()}}),e=>e.status===409);
  console.log('PASS: compras desde caja por piezas/paquetes, pagadas/pendientes, costo unitario, stock y pago posterior sin duplicar; gasto y proveedor, evidencia obligatoria, reintentos sin duplicar, importe/categoría, inventario intacto, corte −280, utilidad solo −80, anulación y turno cerrado.');
 }finally{await c.query('ROLLBACK');c.release();await pool.end();}
})().catch(e=>{console.error(e);process.exitCode=1});
