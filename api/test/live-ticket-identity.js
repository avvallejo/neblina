// Verifica migración y consultas reales de comandas/lista/detalle sin guardar datos.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { pool } = require('../src/db');
const { entregarItemsDeCaja } = require('../src/services/stations');
const { changeOrderItem } = require('../src/services/openOrders');
const { prepareBatch } = require('../src/services/preparationBatch');
const { preparationTrackingSql, deliveryHistorySql, deliverItem } = require('../src/services/preparationTracking');
(async () => {
  assert.equal(process.env.NODE_ENV, 'development');
  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    const { rows: [staff] } = await client.query("SELECT id, sucursal_id, nombre FROM usuarios WHERE sucursal_id IS NOT NULL AND rol IN ('cajero','mostrador','admin') LIMIT 1");
    assert.ok(staff, 'Se requiere personal local de prueba');
    const { rows: [product] } = await client.query("SELECT id FROM productos WHERE sucursal_id=$1 AND activo AND estacion IN ('barra','parrilla') LIMIT 1", [staff.sucursal_id]);
    assert.ok(product);
    const { rows: [order] } = await client.query("INSERT INTO pedidos (origen,sucursal_id,cajero_id,subtotal,total,destino,nombre_ticket) VALUES ('mostrador',$1,$2,10,10,'barra','Prueba nombre ticket') RETURNING *", [staff.sucursal_id,staff.id]);
    await client.query('INSERT INTO pedido_items (pedido_id,producto_id,cantidad,precio_unitario) VALUES ($1,$2,1,10)',[order.id,product.id]);
    const queueSrc = fs.readFileSync(require.resolve('../src/routes/pedidoItems'),'utf8');
    const queueSQL = queueSrc.match(/`(SELECT pi\.\*[\s\S]*?ORDER BY pi\.creado_en, pi\.id)`/)[1];
    const { rows: queue } = await client.query(queueSQL,[staff.sucursal_id,['barra','parrilla']]);
    const line = queue.find(x=>x.pedido_id===order.id);
    assert.ok(line);
    assert.equal(line.nombre_ticket,order.nombre_ticket);
    assert.equal(line.levantado_por_nombre,staff.nombre);
    assert.equal(line.folio,order.folio);
    const orderSrc = fs.readFileSync(require.resolve('../src/routes/pedidos'),'utf8');
    const listSQL = orderSrc.match(/`(SELECT v\.\*, p\.nombre_ticket[\s\S]*?LIMIT 2000)`/)[1];
    const { rows: list } = await client.query(listSQL,[staff.sucursal_id,null]);
    assert.equal(list.find(x=>x.id===order.id).nombre_ticket,order.nombre_ticket);
    const detailSQL = orderSrc.match(/query\('(SELECT v\.\*,p\.nombre_ticket[^']+)'/)[1];
    const { rows: [detail] } = await client.query(detailSQL,[order.id,staff.sucursal_id]);
    assert.equal(detail.nombre_ticket,order.nombre_ticket);
    assert.equal(detail.levantado_por_nombre,staff.nombre);
    const auth = { id: staff.id, rol: 'barista', estaciones: [line.estacion] };
    const batch = { auth, sucursalId: staff.sucursal_id, orderId: order.id, estacion: line.estacion, itemIds: [line.id] };
    const queueForOrder = async () => (await client.query(queueSQL,[staff.sucursal_id,[line.estacion]])).rows.filter(x=>x.pedido_id===order.id);
    assert.equal((await prepareBatch(client,{...batch,action:'iniciar'}))[0].estado,'en_preparacion');
    assert.equal((await queueForOrder()).length,1, 'Iniciar no oculta el ticket');
    const otherStation = line.estacion === 'barra' ? 'parrilla' : 'barra';
    await assert.rejects(()=>prepareBatch(client,{...batch,estacion:otherStation,action:'terminar'}), e=>e.status===403);
    await assert.rejects(()=>prepareBatch(client,{...batch,itemIds:[line.id,'00000000-0000-0000-0000-000000000001'],action:'terminar'}),e=>e.status===409);
    assert.equal((await queueForOrder())[0].estado,'en_preparacion', 'Un lote inválido no termina parcialmente');
    const { rows: [added] } = await client.query('INSERT INTO pedido_items (pedido_id,producto_id,cantidad,precio_unitario) VALUES ($1,$2,2,10) RETURNING *',[order.id,product.id]);
    assert.equal((await prepareBatch(client,{...batch,action:'terminar'})).length,1);
    assert.deepEqual((await queueForOrder()).map(x=>x.estado).sort(),['pendiente','terminado'], 'Conserva terminados y no termina líneas nuevas por accidente');
    assert.equal((await prepareBatch(client,{...batch,action:'terminar'})).length,0, 'Repetir no vuelve a descontar inventario');
    await prepareBatch(client,{...batch,itemIds:[added.id],action:'terminar'});
    assert.ok((await queueForOrder()).every(x=>x.estado==='terminado'), 'Listos persisten al volver a consultar');
    const tracked = async () => (await client.query(preparationTrackingSql,[staff.sucursal_id,false,null])).rows.filter(x=>x.pedido_id===order.id);
    assert.equal((await tracked()).length,2,'Caja ve productos terminados incluso antes de cobrar');
    assert.ok((await tracked()).every(x=>x.terminado_por===staff.id && x.terminado_por_nombre===staff.nombre));
    const delivery = { orderId: order.id, itemId: added.id, sucursalId: staff.sucursal_id, auth, cantidad: 1, cantidadEsperada: 0 };
    const { rows: beforeInventory } = await client.query('SELECT id FROM movimientos_inventario WHERE pedido_item_id=ANY($1::uuid[]) ORDER BY id',[[line.id,added.id]]);
    await deliverItem(client,delivery);
    assert.equal((await tracked()).find(x=>x.id===added.id).cantidad_entregada,1,'Entrega parcial visible');
    await assert.rejects(()=>deliverItem(client,delivery),e=>e.status===409);
    await assert.rejects(()=>deliverItem(client,{...delivery,cantidad:2,cantidadEsperada:1}),e=>e.status===409);
    await assert.rejects(()=>deliverItem(client,{...delivery,sucursalId:'00000000-0000-0000-0000-000000000001'}),e=>e.status===404);
    await deliverItem(client,{...delivery,cantidadEsperada:1});
    await deliverItem(client,{...delivery,itemId:line.id});
    assert.equal((await tracked()).length,0,'Solo sale de Por entregar cuando se entregó todo');
    const { rows: afterInventory } = await client.query('SELECT id FROM movimientos_inventario WHERE pedido_item_id=ANY($1::uuid[]) ORDER BY id',[[line.id,added.id]]);
    assert.deepEqual(afterInventory,beforeInventory,'Entregar no descuenta inventario de nuevo');
    const { rows: [day] } = await client.query("SELECT (now() AT TIME ZONE 'America/Mexico_City')::date::text AS fecha");
    const history = (await client.query(preparationTrackingSql,[staff.sucursal_id,true,day.fecha])).rows.filter(x=>x.pedido_id===order.id);
    assert.equal(history.length,2,'El historial conserva los productos entregados');
    assert.ok(history.every(x=>Number(x.cantidad_entregada)===Number(x.cantidad)));
    await client.query("UPDATE pedido_items SET terminado_en=now()-interval '2 days' WHERE pedido_id=$1",[order.id]);
    assert.equal((await queueForOrder()).length,0,'No acumula tickets terminados de días anteriores');
    // Caja sin preparación: está listo, pero no entregado ni atribuido al barista.
    await client.query("UPDATE productos SET estacion='caja' WHERE id=$1",[product.id]);
    const { rows: [cash] } = await client.query('INSERT INTO pedido_items (pedido_id,producto_id,cantidad,precio_unitario) VALUES ($1,$2,3,10) RETURNING *',[order.id,product.id]);
    await entregarItemsDeCaja(client,order.id);
    let cashLine = (await tracked()).find(x=>x.id===cash.id);
    assert.equal(cashLine.estado,'terminado');
    assert.equal(cashLine.cantidad_entregada,0);
    assert.equal(cashLine.terminado_por,null);
    assert.equal((await queueForOrder()).some(x=>x.id===cash.id),false,'No pasa por barista/parrillero');
    const prepared = (await client.query(preparationTrackingSql,[staff.sucursal_id,true,day.fecha])).rows;
    assert.equal(prepared.some(x=>x.id===cash.id),false,'No cuenta refrescos como trabajo de preparación');
    const cashDelivery={...delivery,itemId:cash.id,cantidadEsperada:0};
    await deliverItem(client,cashDelivery);
    const { rows: [helper] } = await client.query("INSERT INTO usuarios (nombre,rol,pin_hash,sucursal_id,activo) VALUES ('Prueba entrega mostrador','mostrador','no-login-test',$1,false) RETURNING id",[staff.sucursal_id]);
    const helperAuth={id:helper.id,rol:'mostrador',estaciones:['barra','parrilla']};
    await deliverItem(client,{...cashDelivery,auth:helperAuth,cantidadEsperada:1});
    const deliveryHistory=(await client.query(deliveryHistorySql,[staff.sucursal_id,day.fecha])).rows.filter(x=>x.id===cash.id);
    assert.equal(deliveryHistory.length,2);
    assert.deepEqual(new Set(deliveryHistory.map(x=>x.entregado_por)),new Set([staff.id,helper.id]));
    assert.ok(deliveryHistory.every(x=>x.unidades_entregadas_evento===1));
    await assert.rejects(()=>deliverItem(client,cashDelivery),e=>e.status===409);
    // Una devolución real reduce el saldo entregado; aumentar añade unidades por surtir.
    await changeOrderItem(client,{id:order.id,itemId:cash.id,sucursalId:staff.sucursal_id,auth,cantidad:1,cantidadEsperada:3,motivo:'Devolución de prueba',devuelto:true});
    const { rows:[corrected] }=await client.query('SELECT cantidad,cantidad_entregada FROM pedido_items WHERE id=$1',[cash.id]);
    assert.equal(corrected.cantidad_entregada,1);
    await changeOrderItem(client,{id:order.id,itemId:cash.id,sucursalId:staff.sucursal_id,auth,cantidad:2,cantidadEsperada:1,motivo:'Agregar otro refresco',devuelto:false});
    cashLine=(await tracked()).find(x=>x.id===cash.id);
    assert.equal(cashLine.cantidad,2);
    assert.equal(cashLine.cantidad_entregada,1);
    await deliverItem(client,{...cashDelivery,cantidadEsperada:1});
    assert.equal((await tracked()).length,0);
    assert.equal((await client.query(deliveryHistorySql,[staff.sucursal_id,day.fecha])).rows.filter(x=>x.id===cash.id).length,3,'Historial de entregas no se pierde al corregir');
    console.log('PASS: caja sin preparación, entrega explícita/parcial, empleado real por entrega, correcciones y flujo compartido; datos revertidos.');
  } finally { await client.query('ROLLBACK'); client.release(); await pool.end(); }
})().catch(e=>{console.error(e);process.exitCode=1;});
